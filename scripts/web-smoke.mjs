// 一个完整共享流程，直接运行实际 Worker + SQLite，不使用浏览器演示数据。
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { openDatabase } from './web-db.mjs';
const worker = (await import('data:text/javascript;base64,' + Buffer.from(readFileSync(new URL('../dist/server/index.js', import.meta.url))).toString('base64'))).default;
const db = openDatabase();
const origin = 'https://court.test';
const admin = {}, opponent = {}, outsider = {};
const realNow = Date.now;
let clock = realNow();
Date.now = () => clock;
async function call(user, path, input, status = 200) {
  const headers = { Origin: origin };
  if (user.cookie) headers.Cookie = user.cookie;
  if (input !== undefined) headers['Content-Type'] = 'application/json';
  const response = await worker.fetch(new Request(origin + path, { method: input === undefined ? 'GET' : 'POST', headers, ...(input !== undefined ? { body: JSON.stringify(input) } : {}) }), { DB: db });
  const data = await response.json();
  assert.equal(response.status, status, `${path}: ${JSON.stringify(data)}`);
  if (response.headers.get('set-cookie')) user.cookie = response.headers.get('set-cookie').split(';')[0];
  return data;
}
let id;
const act = (user, action, payload, status = 200, requestId = crypto.randomUUID()) => call(user, '/api/action', { groupId: id, action, payload, requestId }, status);
try {
  for (const user of [admin, opponent, outsider]) await call(user, '/api/session', {});
  const created = await call(admin, '/api/create', { name: '流程测试群', memberName: '测试甲', gender: 'male' });
  id = created.group.id;
  let state = await act(admin, 'addMember', { name: '测试乙', gender: 'male' });
  const b = state.group.members.at(-1).id;
  state = await act(admin, 'addMember', { name: '测试丙', gender: 'male' });
  const c = state.group.members.at(-1).id;
  await call(outsider, '/api/group?id=' + id, undefined, 403);
  await act(outsider, 'join', {}, 400);
  await call(opponent, '/api/join', { invite: created.invite, requestId: crypto.randomUUID() });
  await act(opponent, 'addMember', { name: '越权', gender: 'male' }, 403);
  await act(opponent, 'claim', { memberId: b });
  state = await call(admin, '/api/group?id=' + id);
  assert.equal(state.group.claims.length, 1);
  await act(admin, 'approveClaim', { claimId: state.group.claims[0].id });
  assert.equal((await call(opponent, '/api/group?id=' + id)).group.meId, b);
  state = await act(admin, 'addGuest', { name: '临时测试', gender: 'male' });
  const guest = state.group.members.at(-1).id;
  const match = { type: 'doubles', teams: [['p1', guest], [b, c]], target: 21, rule: 'sudden', cap: 30, ranked: true, games: [[21, 18]], playedAt: clock - 10000 };
  const draftRequest = crypto.randomUUID();
  const draft = await act(admin, 'saveDraft', match, 200, draftRequest);
  await act(admin, 'saveDraft', match, 200, draftRequest);
  state = await call(opponent, '/api/group?id=' + id);
  assert.equal(state.group.matches.length, 1, '重复请求不能新增两场');
  assert.equal(state.group.matches[0].status, 'draft');
  const draftId = draft.createdId;
  await act(opponent, 'edit', { ...match, matchId: draftId, revision: 1 }, 403);
  await act(admin, 'edit', { ...match, games: [[21, 18], [18, 21]], matchId: draftId, revision: 1 });
  state = await call(opponent, '/api/group?id=' + id);
  assert.equal(state.group.matches[0].winner, null);
  await act(opponent, 'object', { matchId: draftId, revision: 1, reason: '过时版本' }, 400);
  await act(opponent, 'confirm', { matchId: draftId, revision: 2 });
  const exported = await call(admin, '/api/export?id=' + id);
  assert.equal(exported.matches[0].games.length, 2);
  const D = (await import('../miniprogram/lib/domain.js')).default;
  const standings = D.buildStandings(exported, clock);
  for (const member of ['p1', b, c]) assert.equal(standings.people[member].points, 1);
  assert.equal(standings.people[guest], undefined);
  const timeout = await act(admin, 'record', { ...match, type: 'singles', teams: [['p1'], [b]], games: [[21, 18]], playedAt: clock - 7 * 86400000 });
  assert.equal(timeout.group.matches.at(-1).status, 'pending', '补录旧比赛仍从提交开始计24小时');
  clock += 86400001;
  state = await call(opponent, '/api/group?id=' + id);
  assert.equal(state.group.matches.at(-1).confirmationMethod, 'timeout');
  assert.equal(state.group.matches.at(-1).confirmedAt, clock - 1);
  const key = (await call(opponent, '/api/login-code')).loginCode;
  const recovered = {};
  await call(recovered, '/api/session', { loginCode: key });
  assert.equal((await call(recovered, '/api/group?id=' + id)).group.meId, b);
  const forged = await worker.fetch(new Request(origin + '/api/action', { method: 'POST', headers: { Origin: 'https://outside.test', Cookie: admin.cookie, 'Content-Type': 'application/json' }, body: '{}' }), { DB: db });
  assert.equal(forged.status, 403);
  console.log('网页共享流程通过：独立身份、认领审核、权限隔离、草稿恢复、两局平局、临时队员、提交去重、24小时结算、换机恢复与跨站请求拦截。');
} finally { Date.now = realNow; db.close(); }
